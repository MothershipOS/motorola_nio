#!/usr/bin/env python3
"""Generate a DTS include that lets ABL apply the stock nio dtbo harmlessly.

ABL applies the matching dtbo-partition overlay to whatever base DTB it boots,
including one supplied by `fastboot boot`. The stock overlay resolves its
fragment targets through __fixups__, so a mainline DTB without matching
__symbols__ makes that step fail. This include maps every fixup label to its own
disabled dummy node under a disabled parent, so the overlay content lands there
and is never probed. Reads a local dtbo image backup; never touches a phone.
"""
import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / 'kernel/dts/sm8250-motorola-nio-abl-sink.dtsi'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('dtbo', type=Path, help='Backed-up dtbo partition image')
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    data = args.dtbo.read_bytes()
    magic, _total, _header, entry_size, count, entries = struct.unpack_from('>6I', data)
    if magic != 0xd7b7ab1e:
        raise SystemExit('Not an Android dtbo image')
    labels = set()
    with tempfile.TemporaryDirectory() as tmp:
        for index in range(count):
            size, offset = struct.unpack_from('>2I', data, entries + index * entry_size)
            blob = Path(tmp) / f'{index}.dtbo'
            blob.write_bytes(data[offset:offset + size])
            listing = subprocess.run(['fdtget', '-p', str(blob), '/__fixups__'],
                                     capture_output=True, text=True, check=True).stdout
            labels.update(listing.split())
    bad = [label for label in labels if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', label)]
    if bad:
        raise SystemExit('Unexpected fixup label names: ' + ', '.join(sorted(bad)))
    labels = sorted(labels)
    digest = hashlib.sha256(data).hexdigest()
    lines = [
        '// SPDX-License-Identifier: BSD-3-Clause',
        f'/* Generated by tools/gen_abl_overlay_sink.py from dtbo sha256 {digest}.',
        ' * Fastboot-boot only: absorbs the stock ABL dtbo overlay. Do not edit. */',
        '',
        '/ {',
        '\tabl_overlay_sink: abl-overlay-sink {',
        '\t\tstatus = "disabled";',
        '\t\t/* References make dtc emit a phandle for every sink node. */',
        '\t\tsink-nodes = <' + ' '.join(f'&abl_sink_{label}' for label in labels) + '>;',
        '',
    ]
    for label in labels:
        lines += [f'\t\tabl_sink_{label}: {label} {{', '\t\t\tstatus = "disabled";', '\t\t};']
    lines += ['\t};', '', '\t__symbols__ {']
    lines += [f'\t\t{label} = "/abl-overlay-sink/{label}";' for label in labels]
    lines += ['\t};', '};', '']
    args.output.write_text('\n'.join(lines))
    print(f'{len(labels)} overlay labels -> {args.output.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
