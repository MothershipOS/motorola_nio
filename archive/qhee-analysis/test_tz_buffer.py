#!/usr/bin/env python3
"""Check original TZ buffer boundaries, finite FIFO input and explicit slice joins."""
import hashlib
import json
from pathlib import Path
import struct
import unittest
from unittest.mock import patch
from tz_buffer import *

class TzBufferTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.out=ROOT/'kernel-work/out/qhee-tz-buffer-tests';cls.out.mkdir(parents=True,exist_ok=True)
        cls.cases=json.loads((ROOT/'kernel-work/out/qhee-tz-query-tests/results.json').read_text())
        cls.pins={n:hashlib.sha256((ROOT/'backups/nio-firmware-20260927T163534Z'/n).read_bytes()).hexdigest()
                  for n in ('hyp_a.img','tz_a.img','xbl_a.img','devcfg_a.img','abl_a.img')}

    def test_pinned_registry_backend_and_windows(self):
        r=inventory();self.assertEqual(r['firmware_sha256'],PINNED_TZ)
        self.assertEqual(r['registry']['descriptor']['arginfo'],'0x22')
        self.assertEqual(r['registry']['descriptor']['flags'],'0x1')
        self.assertEqual(r['registry']['descriptor']['handler'],'0x1c054b30')
        self.assertEqual(r['backend_selector'],'0x1c042c8c');self.assertEqual(r['mmio_base'],'0x791000')
        self.assertEqual(r['copy_callback'],'0x1c050c88')
        self.assertEqual(r['source_sha256'],hashlib.sha256(Path(__file__).with_name('tz_buffer.py').read_bytes()).hexdigest())
        with patch('tz_handoff.Path.read_bytes',return_value=b'changed'):
            with self.assertRaisesRegex(ValueError,'pinned TZ'):inventory()

    def test_captured_ten_requests_and_original_marshalling(self):
        results=[];self.assertEqual(len(self.cases),10)
        for c in self.cases:
            trace=Path(c['trace']);data=trace.read_bytes();t=json.loads(data);last=t['xbl_prefix_checkpoints'][-1]
            self.assertEqual(last['registers']['pc'],'0x9fc28468')
            words=[int(last['registers']['x'+str(i)],16) for i in range(14)];r=run(words)
            self.assertEqual(r['decode']['stop'],'0x1c065c28');self.assertIsNone(r['decode']['validation_status'])
            self.assertEqual(r['handler']['stop'],'0x1c065b0c')
            self.assertEqual(r['reply_x0_x7'],['0x0','0x8']+['0x0']*6)
            self.assertEqual(r['return']['buffer_hex'],'cc444444dd444444')
            self.assertFalse(any(int(v['address'],16)==0x801cba78 for stage in ('decode','handler','backend') for v in r[stage]['reads']))
            d=self.out/(c['profile']+'-'+c['clock']+'-'+('el2' if c['el2'] else 'stock'));d.mkdir(exist_ok=True)
            (d/'input-trace.json').write_bytes(data);(d/'slices.json').write_text(json.dumps(r,indent=2)+'\n')
            results.append({**c,'input_snapshot':str(d/'input-trace.json'),'input_snapshot_sha256':hashlib.sha256(data).hexdigest(),
                            'slices':str(d/'slices.json'),'scope':'Snapshot of a prior full modeled QHEE/XBL trace; path may later be regenerated by another suite.'})
        (self.out/'results.json').write_text(json.dumps(results,indent=2)+'\n')

    def test_count_types_and_smc32_normalization(self):
        for info,status in ((0,'0xfffffffb'),(1,'0xfffffffb'),(2,'0xfffffff6'),(0x12,'0xfffffff6'),(0x32,'0xfffffff6'),(0x42,'0xfffffff6')):
            r=decode([0x2000a01,info,BUFFER,8]+[0]*10)
            self.assertEqual(r['stop'],'0x1c06748c');self.assertEqual(r['validation_status'],status)
        words=[0x2000a01,0x22,0xfeed00009fc356c0,0xffff000000000008]+[0]*10
        r=run(words);self.assertEqual(struct.unpack_from('<2Q',bytes.fromhex(r['decode']['normalized_hex']),16),(BUFFER,8))
        with self.assertRaisesRegex(ValueError,'fourteen'):decode([1])
        r=decode([0x2000a01,0x22,BUFFER,8]+[0]*10);desc=bytearray(bytes.fromhex(r['descriptor_hex']));struct.pack_into('<Q',desc,16,0x1c06705c)
        with self.assertRaisesRegex(ValueError,'restricted'):handler(r['normalized_hex'],desc.hex())

    def test_handler_pointer_and_length_limits(self):
        for address,size,accepted in ((0,8,False),(BUFFER,0,False),(BUFFER,1,True),(BUFFER,8,True),(BUFFER,512,True),(BUFFER,513,False)):
            d=decode([0x2000a01,0x22,address,size]+[0]*10);f,r=handler(d['normalized_hex'],d['descriptor_hex'])
            self.assertEqual(r['stop'],'0x1c065b0c' if accepted else '0x1c04d62c')
            self.assertEqual(r['buffer_hex'],'00'*8)
            self.assertTrue(all(not BUFFER<=int(w['address'],16)<BUFFER+8 for w in r['writes']))
            entry=next(p['registers'] for p in r['checkpoints'] if p['pc']=='0x1c054b30')
            self.assertEqual([entry['x0'],entry['x1']],[hex(address),hex(size)])
            self.assertEqual(entry['x2'],'0x9000efa0')
            self.assertIn('0x1c0679f0',r['pcs'])

    def test_original_pointer_overflow_and_page_bounds(self):
        r=pointer_arithmetic();self.assertEqual(r['stop'],'0x1c0c0b68')
        self.assertEqual([r['registers']['x'+str(i)] for i in range(4)],['0x9fc35000','0x1000','0x8','0x0'])
        for address,size in ((BUFFER,0),(0xffffffffffffffff,8),(0xffffffffffffffff-4,8),(0xfffffffffffff000,1)):
            r=pointer_arithmetic(address,size);self.assertEqual(r['stop'],hex(RETURN));self.assertEqual(r['registers']['x0'],'0x0')
        r=pointer_arithmetic(0xffffffffffffefff,1);self.assertEqual(r['stop'],'0x1c0c0b68')

    def test_original_backend_and_clock_dependency(self):
        r=run();b=r['backend']
        self.assertEqual(b['stop'],'0x1c0549c8')
        self.assertEqual([b['registers']['x0'],b['registers']['x1']],['0x1','0x1'])
        for pc in ('0x1c03d0d0','0x1c03e058','0x1c042c8c'):self.assertIn(pc,b['pcs'])
        self.assertFalse(any(MMIO<=int(a['address'],16)<MMIO+0x1000 for a in b['reads']))
        setup=r['backend_setup'];self.assertEqual(setup['stop'],'0x1c0666dc');self.assertEqual(setup['registers']['x0'],'0x4')
        self.assertIn('0x1c05495c',setup['pcs'])

    def test_finite_original_fifo_xor_and_copy(self):
        r=fifo_slice();self.assertEqual(r['stop'],'0x1c042ec8');self.assertEqual(r['produced_bytes'],8)
        self.assertEqual(r['fifo_samples'],['0x11223344','0x55667788','0x99aabbcc','0xddeeff11']);self.assertEqual(r['ready_reads'],4)
        self.assertEqual(r['buffer_hex'],'cc444444dd444444')
        self.assertEqual(r['guard_before_hex'],r['guard_after_hex']);self.assertEqual(r['guard_after_hex'],'a5'*16)
        self.assertIn('0x1c03d3dc',r['pcs']);self.assertIn('0x1c050c88',r['pcs'])
        writes=[v for v in r['writes'] if BUFFER<=int(v['address'],16)<BUFFER+8]
        self.assertEqual(sum(v['size'] for v in writes),8)
        self.assertTrue(all(BUFFER<=int(v['address'],16) and int(v['address'],16)+v['size']<=BUFFER+8 for v in writes))
        alternative=fifo_slice((0x1,0x10001,0x2,0x20002));self.assertEqual(alternative['buffer_hex'],'0000010000000200')

    def test_fifo_unknown_and_filtered_input_fail_closed(self):
        with self.assertRaisesRegex(ValueError,'four uint32'):fifo_slice((1,2))
        for samples in ((0,0x55667788,0x99aabbcc,0xddeeff11),(0x11223344,1,0x99aabbcc,0xddeeff11)):
            with self.assertRaisesRegex(ValueError,'bound exhausted|fixture exhausted'):fifo_slice(samples)
        f=Slice([1,2,3,4]);f.u.reg_write(UC_ARM64_REG_X0,MMIO+8)
        with self.assertRaisesRegex(ValueError,'Unknown PRNG MMIO'):f.execute(0x1c03d468)
        f=Slice();f.u.reg_write(UC_ARM64_REG_X0,BUFFER+8);f.u.reg_write(UC_ARM64_REG_X0+1,0);f.u.reg_write(UC_ARM64_REG_X0+2,1)
        with self.assertRaisesRegex(ValueError,'Unexpected TZ buffer write'):f.execute(0x1c050b8c)

    def test_original_return_and_short_count_boundary(self):
        r=run();self.assertEqual(r['return']['stop'],hex(RETURN));self.assertEqual(r['return']['registers']['sp'],hex(SP))
        self.assertEqual(r['reply_x0_x7'],['0x0','0x8']+['0x0']*6)
        self.assertEqual(r['post_backend']['stop'],'0x1c0c72e4');self.assertEqual(r['post_backend']['registers']['x1'],'0x8')
        self.assertEqual(len(r['joins']),4)
        for count in (0,4):
            r=run(produced=count);self.assertEqual(r['return']['stop'],'0x1c04d62c');self.assertIsNone(r['reply_x0_x7'])
            self.assertEqual(r['return']['buffer_hex'],('cc444444dd444444'[:2*count]+'00'*(8-count)))
        with self.assertRaisesRegex(ValueError,'outside buffer'):run(produced=9)
        for n,h in self.pins.items():self.assertEqual(hashlib.sha256((ROOT/'backups/nio-firmware-20260927T163534Z'/n).read_bytes()).hexdigest(),h)

if __name__=='__main__':unittest.main()
